// Sesiuni de relaxare ghidate (v2.0.0): temporizator pe pași, pauză, sărire, jurnal. Rulare: node tests/sesiuni.test.mjs
import {createRequire} from 'module'; import path from 'node:path'; import {fileURLToPath} from 'node:url';
const require = createRequire(process.env.PW_ROOT || import.meta.url); const {chromium} = require('playwright');
const HERE = path.dirname(fileURLToPath(import.meta.url)); const FILE = 'file://' + path.join(HERE, '..', 'index.html');
let ok = 0, bad = 0; const t = (n, c, x) => { if (c) { ok++; console.log('  ok  ', n); } else { bad++; console.log('  FAIL', n, x ?? ''); } };
const b = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox']});
const ctx = await b.newContext({viewport: {width: 1100, height: 900}, locale: 'en-US'});
const net = []; await ctx.route(/^https?:/, r => { net.push(r.request().url()); r.abort(); });
const p = await ctx.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
await p.clock.install({time: new Date('2026-10-26T10:00:00Z')});
await p.goto(FILE); await p.waitForTimeout(300); await p.selectOption('#uiLang', 'en');
await p.click('a[data-target="sesiuni"]');
t('panou vizibil', await p.isVisible('#p-sesiuni'));
t('titlu tradus (EN)', /Relaxation sessions/.test(await p.textContent('#p-sesiuni h2')));
t('avertisment fără dovezi științifice', /no scientific evidence/.test(await p.textContent('#p-sesiuni')));
t('lista are 8 pași (gassho + 6 poziții + încheiere)', (await p.$$('#ssList li')).length === 8);
await p.selectOption('#ssPreset', '1'); await p.uncheck('#ssSound');
t('preset scurt: 60 s / poziție', (await p.textContent('#ssList li:nth-child(2)')).includes('01:00'));
await p.click('#ssStart');
t('pas 1 = Gassho', /Gassho/.test(await p.textContent('#ssStep')));
t('Start dezactivat, Pauză activă', await p.isDisabled('#ssStart') && !(await p.isDisabled('#ssPause')));
await p.clock.runFor(20000);
t('ceas: 00:40 după 20 s', (await p.textContent('#ssClock')) === '00:40', await p.textContent('#ssClock'));
await p.click('#ssPause'); await p.clock.runFor(500); const c0 = await p.textContent('#ssClock'); await p.clock.runFor(30000);
t('pauză: ceasul nu avansează', (await p.textContent('#ssClock')) === c0 && ['00:40', '00:39'].includes(c0), [c0, await p.textContent('#ssClock')]);
await p.click('#ssPause'); await p.clock.runFor(42000);
t('trecere la pasul 2 (Creștet)', /Crown|Top|Vertex|Creștet|Crown of/i.test(await p.textContent('#ssStep')) , await p.textContent('#ssStep'));
t('aria-current pe pasul activ', (await p.getAttribute('#ssList li:nth-child(2)', 'aria-current')) === 'step');
await p.click('#ssSkip');
t('Pasul următor sare la poziția 2', /\b2 of 8|Step 3 of 8/.test(await p.textContent('#ssMeta')), await p.textContent('#ssMeta'));
for (let i = 0; i < 5; i++) { await p.click("#ssSkip"); }
t('ultimul pas = Încheiere', /Closing/.test(await p.textContent('#ssStep')), await p.textContent('#ssStep'));
await p.clock.runFor(61000);
t('sesiune încheiată', /Session complete/.test(await p.textContent('#ssStep')), await p.textContent('#ssStep'));
t('buton jurnal vizibil și contor salvat', await p.isVisible('#ssLog') && /completed on this device: 1/.test(await p.textContent('#ssHist')));
await p.click('#ssLog');
t('jurnal conține linia sesiunii', /guided relaxation session/.test(await p.inputValue('#journalText')));
t('stocare locală reiki.sesiuni', await p.evaluate(() => JSON.parse(localStorage.getItem('reiki.sesiuni')).length === 1));
await p.click('#ssStart'); await p.click('#ssStop');
t('Oprește: mesaj și fără contor nou', /Session stopped/.test(await p.textContent('#ssStep')) && await p.evaluate(() => JSON.parse(localStorage.getItem('reiki.sesiuni')).length === 1));
await p.selectOption('#uiLang', 'ro');
t('RO: titlu', /Sesiuni de relaxare/.test(await p.textContent('#p-sesiuni h2')));
t('fără erori/CSP', errs.length === 0, errs); t('0 cereri de rețea', net.length === 0, net);
await b.close(); console.log(`\n${ok} reușite, ${bad} eșuate`); process.exit(bad ? 1 : 0);
